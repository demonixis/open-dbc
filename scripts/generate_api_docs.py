def toc_html(entries: list[tuple]) -> str:
    out = []
    for entry in entries:
        sym, anchor = entry[0], entry[1]
        attr = ""
        if len(entry) > 2 and entry[2]:
            attr += f' data-status="{entry[2]}"'
        if len(entry) > 3 and entry[3]:
            attr += f' data-profile="{entry[3]}"'
        out.append(f'<a href="#{anchor}"{attr}>{esc(sym)}</a>')
    return "".join(out)


def counts_line(rows: list[dict]) -> str:
    total = len(rows)
    impl = sum(1 for r in rows if r["runtime_status"] == "Implemented")
    stubs = sum(1 for r in rows if r["runtime_status"].startswith("Compatibility stub"))
    return (f"{total} entries — {impl} implemented in OpenDBC "
            f"({impl * 100 // total if total else 0}%), {stubs} compatibility stubs.")


