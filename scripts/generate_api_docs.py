MEDIA_RE = re.compile(
    r'"([^"\n]+\.(?:bmp|png|jpe?g|tga|dds|x|3ds|mdl|md[23]|dbo|wav|mid|mp3|ogg|'
    r'avi|mpg|fx|vsh|psh|dba))"', re.I)

_WORD_RE = re.compile(r"[A-Z0-9_#$]+")


def _strip_code_line(line: str) -> str:
    """Remove comments and string literals; return uppercased code text."""
    stripped = line.lstrip()
    low = stripped.lower()
    if low.startswith("rem") and (len(stripped) == 3 or not stripped[3].isalnum()):
        return ""
    if low.startswith("`") or low.startswith("//"):
        return ""
    out, in_str = [], False
    i = 0
    while i < len(line):
        ch = line[i]
        if in_str:
            if ch == '"':
                in_str = False
            i += 1
            continue
        if ch == '"':
            in_str = True
            i += 1
            continue
        if ch == "`" or line[i:i + 2] == "//":
            break
        out.append(ch)
        i += 1
    return "".join(out).upper()


def build_symbol_matcher(rows: list[dict]) -> dict[str, list[tuple[tuple[str, ...], str]]]:
    """Index core callables by first word for longest-match scanning."""
    matcher: dict[str, list[tuple[tuple[str, ...], str]]] = {}
    seen = set()
    for r in rows:
        if r["surface"] != "Core" or r["kind"] not in ("Command", "Function"):
            continue
        symbol = r["symbol"]
        if symbol in seen:
            continue
        seen.add(symbol)
        words = tuple(symbol.split())
        matcher.setdefault(words[0], []).append((words, symbol))
    for lst in matcher.values():
        lst.sort(key=lambda e: -len(e[0]))
    return matcher


def match_commands(lines: list[str], matcher: dict) -> list[str]:
    """Return catalogue symbols used, ordered by first appearance."""
    found: "OrderedDict[str, None]" = OrderedDict()
    for line in lines:
        code = _strip_code_line(line)
        if not code:
            continue
        words = _WORD_RE.findall(code)
        i = 0
        while i < len(words):
            hit_len = 1
            for cand_words, symbol in matcher.get(words[i], ()):
                if tuple(words[i:i + len(cand_words)]) == cand_words:
                    found.setdefault(symbol)
                    hit_len = len(cand_words)
                    break
            i += hit_len
    return list(found)


_HEADER_META_RE = re.compile(r"^\s*rem\s*\*?\s*(title|project|author|date|created)\s*:\s*(.+)$", re.I)
_DECOR_RE = re.compile(r"^[\s*=\-#~_.]*$")


def analyze_example(path: Path, matcher: dict) -> dict:
    raw = path.read_text(encoding="cp1252", errors="replace")
    lines = raw.splitlines()
    low = raw.lower()

    title = author = None
    desc_lines: list[str] = []
    for line in lines[:25]:
        stripped = line.strip()
        m = _HEADER_META_RE.match(line)
        if m:
            key, value = m.group(1).lower(), m.group(2).strip()
            if key in ("title", "project") and not title:
                title = value
            elif key == "author" and not author:
                author = value
            continue
        low_line = stripped.lower()
        if low_line.startswith("rem"):
            body = stripped[3:].strip()
            if _DECOR_RE.match(body) or "example program" in body.lower():
                if desc_lines:
                    break  # closing separator after the description
                continue
            if not title:
                title = body
            else:
                desc_lines.append(body)
        elif not stripped:
            if desc_lines:
                break  # blank line ends the header block
        else:
            break  # first code line ends the header block
    if not title:
        title = path.stem

    code_lines = [l for l in lines if _strip_code_line(l).strip()]
    functions = re.findall(r"^\s*function\s+([A-Za-z_][\w#$]*)", raw, re.I | re.M)
    labels = [l for l in re.findall(r"^\s*([A-Za-z_]\w*):\s*$", raw, re.M)
              if l.lower() not in ("http", "https")]
    includes = re.findall(r'#include\s+"([^"]+)"', raw, re.I)
    media = []
    for m in MEDIA_RE.finditer(raw):
        f = m.group(1)
        if not f.lower().endswith(".dba") and f not in media:
            media.append(f)

    return {
        "path": path,
        "rel": path.relative_to(ROOT).as_posix(),
        "title": title,
        "author": author,
        "desc": " ".join(desc_lines),
        "total": len(lines),
        "code": len(code_lines),
        "functions": functions,
        "labels": labels,
        "gosubs": len(re.findall(r"\bgosub\b", low)),
        "main_loop": bool(re.search(r"^\s*do\b", low, re.M) and re.search(r"^\s*loop\b", low, re.M)),
        "sync_on": "sync on" in low,
        "wait_key_end": bool(re.search(r"\bwait key\b[^\n]*$", low.rstrip())),
        "dims": len(re.findall(r"^\s*dim\b", low, re.M)),
        "has_data": bool(re.search(r"^\s*data\b", low, re.M)),
        "types": len(re.findall(r"^\s*type\b", low, re.M)),
        "includes": includes,
        "media": media,
        "commands": match_commands(lines, matcher),
        "source": raw,
    }


def _natural_key(path: Path):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", path.name.lower())]


def render_example_entry(info: dict, anchor: str, profile: str, anchor_map: dict) -> str:
    out = [f'<article class="cmd" id="{anchor}">']
    badge = f'<span class="badge {profile}">{profile}</span>'
    out.append(f'<h3>{esc(info["title"])} {badge}'
               f'<span class="badge kind">Example</span></h3>')
    meta = f'<code>{esc(info["rel"])}</code> · {info["total"]} lines ({info["code"]} code)'
    if info["author"]:
        meta += f" · author: {esc(info['author'])}"
    out.append(f'<p class="ex-path">{meta}</p>')
    if info["desc"]:
        out.append(f'<p class="desc">{esc(info["desc"])}</p>')

    # --- How it's built -------------------------------------------------
    build: list[str] = []
    if info["main_loop"]:
        shape = "Frame-driven: a main <code>do … loop</code> runs every frame"
        shape += (" under <code>sync on</code>, so the program calls <code>sync</code> "
                  "itself to present each frame." if info["sync_on"]
                  else " with automatic screen refresh.")
    else:
        shape = "Linear: runs once from top to bottom"
        shape += (", then holds the result on screen with <code>wait key</code>."
                  if info["wait_key_end"] else ".")
    build.append(f"<li><strong>Program shape.</strong> {shape}</li>")

    logic = []
    if info["functions"]:
        names = ", ".join(f"<code>{esc(n)}</code>" for n in info["functions"][:8])
        extra = f" (+{len(info['functions']) - 8} more)" if len(info["functions"]) > 8 else ""
        logic.append(f"{len(info['functions'])} user function(s): {names}{extra}")
    if info["labels"] and info["gosubs"]:
        names = ", ".join(f"<code>{esc(n)}</code>" for n in info["labels"][:8])
        extra = f" (+{len(info['labels']) - 8} more)" if len(info["labels"]) > 8 else ""
        logic.append(f"{len(info['labels'])} GOSUB subroutine(s): {names}{extra}")
    if logic:
        build.append(f"<li><strong>Structure.</strong> {'; '.join(logic)}.</li>")

    data = []
    if info["dims"]:
        data.append(f"{info['dims']} array(s) declared with <code>DIM</code>")
    if info["has_data"]:
        data.append("constant tables in <code>DATA</code> blocks read with <code>READ</code>")
    if info["types"]:
        data.append(f"{info['types']} user-defined <code>TYPE</code>(s)")
    if info["includes"]:
        inc = ", ".join(f"<code>{esc(i)}</code>" for i in info["includes"])
        data.append(f"pulls in {inc} via <code>#INCLUDE</code>")
    if data:
        build.append(f"<li><strong>Data.</strong> {'; '.join(data)}.</li>")

    if info["media"]:
        files = ", ".join(f"<code>{esc(f)}</code>" for f in info["media"][:6])
        extra = f" (+{len(info['media']) - 6} more)" if len(info["media"]) > 6 else ""
        build.append(f"<li><strong>Assets.</strong> Loads {len(info['media'])} media file(s) "
                     f"from the example folder: {files}{extra}.</li>")

    out.append('<h4>How it is built</h4><ul class="build-list">' + "".join(build) + "</ul>")

    # --- Commands used, linked into the reference -----------------------
    if info["commands"]:
        chips = []
        for symbol in info["commands"][:24]:
            url = anchor_map.get(symbol)
            if url:
                chips.append(f'<a class="chip" href="{url}">{esc(symbol)}</a>')
            else:
                chips.append(f'<span class="chip">{esc(symbol)}</span>')
        if len(info["commands"]) > 24:
            chips.append(f'<span class="chip chip-more">+{len(info["commands"]) - 24} more</span>')
        out.append(f'<h4>Commands used ({len(info["commands"])})</h4>'
                   f'<div class="chips">{"".join(chips)}</div>')

    # --- Source ---------------------------------------------------------
    src_lines = info["source"].splitlines()
    if info["total"] <= 150:
        shown = info["source"]
        note = ""
    else:
        shown = "\n".join(src_lines[:40])
        note = (f'<p class="src-note">First 40 lines shown — {info["total"] - 40} more in '
                f'<code>{esc(info["rel"])}</code>.</p>')
    out.append(f'<details class="src-details"><summary>View source ({info["total"]} lines)</summary>'
               f'<pre class="example"><code>{highlight_dba(shown)}</code></pre>{note}</details>')
    out.append("</article>")
    return "".join(out)


def _collect_examples(base: Path, folder_titles: dict) -> list[tuple[str, list[Path]]]:
    """Return [(section title, [files])] for a tutorials tree."""
    sections = []
    for folder in sorted(p for p in base.iterdir() if p.is_dir()):
        files = sorted(folder.rglob("*.dba"), key=_natural_key)
        if files:
            title = folder_titles.get(folder.name, folder.name.title())
            sections.append((f"Tutorials — {title}", files))
    return sections


