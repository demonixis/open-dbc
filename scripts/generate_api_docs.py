_TOKEN_RE = re.compile(r'"[^"]*"?|[A-Za-z_][A-Za-z0-9_#$]*|\d+\.\d+|\d+|.')


def highlight_dba(code: str) -> str:
    """Server-side DBA syntax highlighting: comments, strings, numbers, keywords."""
    out = []
    for line in code.split("\n"):
        stripped = line.lstrip()
        low = stripped.lower()
        if low.startswith("rem") and (len(stripped) == 3 or not stripped[3].isalnum()) \
           or low.startswith("remstart") or low.startswith("remend") \
           or low.startswith("`") or low.startswith("//"):
            out.append(f'<span class="c-com">{esc(line)}</span>')
            continue
        parts = []
        for m in _TOKEN_RE.finditer(line):
            tok = m.group(0)
            if tok.startswith('"'):
                parts.append(f'<span class="c-str">{esc(tok)}</span>')
            elif tok[0].isdigit():
                parts.append(f'<span class="c-num">{esc(tok)}</span>')
            elif tok == "`" or (tok == "/" and line[m.end():m.end() + 1] == "/"):
                parts.append(f'<span class="c-com">{esc(line[m.start():])}</span>')
                break
            elif tok[0].isalpha() or tok[0] == "_":
                if tok.upper() in HIGHLIGHT_KEYWORDS or tok.upper() == "REM":
                    parts.append(f'<span class="c-kw">{esc(tok)}</span>')
                else:
                    parts.append(esc(tok))
            else:
                parts.append(esc(tok))
        out.append("".join(parts))
    return "\n".join(out)


def slugify(symbol: str) -> str:
    if symbol in OPERATOR_IDS:
        return OPERATOR_IDS[symbol]
    s = symbol.lower().replace("$", "-str")
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s or "sym"


