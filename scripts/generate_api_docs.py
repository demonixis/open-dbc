def value_for_param(symbol: str, name: str, ptype: str) -> str:
    upper = name.upper()
    if ptype == "string" or upper.endswith("$") or "FILENAME" in upper or "STRING" in upper:
        if any(w in symbol for w in ("LOAD", "SAVE", "OPEN", "MAKE FILE", "EXECUTE")):
            return '"media/file.dat"'
        return '"text"'
    if ptype == "any array":
        return "myarray()"
    if ptype == "output":
        return "result"
    for keys, value in NAME_VALUES:
        if any(k in upper.split() or k == upper for k in keys):
            return value
    for keys, value in NAME_VALUES:
        if any(k in upper for k in keys):
            return value
    return "1"


def auto_example(symbol: str, kind: str, params: list[str], ret: str,
                 names: list[str] | None, category: str) -> str:
    names = names or [generic_param_name(t, i + 1) for i, t in enumerate(params)]
    values = [value_for_param(symbol, n, t) for n, t in zip(names, params)]

    setup: list[str] = []
    first_word = symbol.split()[0]
    for name in names:
        for key, line in SETUP_LINES.items():
            if key in name.upper() and key not in symbol.split() \
               and first_word not in ("MAKE", "CREATE", "LOAD", "DELETE") \
               and line.split("\n")[-1].upper().split()[0] != first_word:
                if line not in setup:
                    setup.append(line)
                break

    call_args = ", ".join(values)
    lines = [f"rem {symbol} — generated example"]
    lines += setup
    if kind == "Function":
        var = "result$" if ret == "string" else "result"
        lines.append(f"{var} = {symbol.lower()}({call_args})")
        lines.append(f"print {var}")
    else:
        lines.append(f"{symbol.lower()} {call_args}".rstrip())
    if category in ("basic2d", "sprite", "bobs", "text", "basic3d", "camera",
                    "light", "matrix", "image", "bitmap", "screen"):
        lines.append("wait key")
    return "\n".join(lines)


