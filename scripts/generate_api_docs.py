def parse_overloads(typed: str) -> list[tuple[list[str], str]]:
    """'number, number -> void; none -> real' -> [([t1,t2], ret), ([], ret)]."""
    overloads = []
    for part in typed.split(";"):
        part = part.strip()
        if not part or "->" not in part:
            continue
        left, ret = part.rsplit("->", 1)
        left = left.strip()
        params = [] if left in ("", "none") else [p.strip() for p in left.split(",")]
        overloads.append((params, ret.strip()))
    return overloads


def generic_param_name(ptype: str, index: int) -> str:
    base = {
        "number": "Number", "real": "Real", "integer": "Integer",
        "string": "String", "output": "OutVar", "any array": "Array",
        "any": "Value",
    }.get(ptype, "Value")
    name = f"{base}{index}"
    if ptype == "string":
        name += "$"
    if ptype == "any array":
        name = f"Array{index}()"
    return name


def help_param_names(symbol: str, kind: str, syntax: str, arity: int) -> list[str] | None:
    """Extract authentic parameter names from a DBC help SYNTAX block."""
    for line in syntax.split("\n"):
        line = line.strip()
        if not line:
            continue
        if "=" in line and "(" in line:  # function form: Return Value=NAME(args)
            call = line.split("=", 1)[1].strip()
            upper = call.upper()
            if not upper.startswith(symbol):
                continue
            inner = call[len(symbol):].strip()
            if inner.startswith("(") and inner.endswith(")"):
                inner = inner[1:-1]
            names = [n.strip() for n in inner.split(",") if n.strip()]
            if len(names) == arity:
                return names
        elif kind == "Command" and line.upper().startswith(symbol):
            rest = line[len(symbol):].strip()
            if not rest:
                continue
            names = [n.strip().strip("[]") for n in rest.split(",") if n.strip()]
            if len(names) == arity:
                return names
    return None


def build_signature(symbol: str, kind: str, params: list[str], ret: str,
                    names: list[str] | None, min_arity: int | None) -> str:
    parts = []
    for i, ptype in enumerate(params):
        name = names[i] if names and i < len(names) else generic_param_name(ptype, i + 1)
        if min_arity is not None and i >= min_arity:
            name = f"[{name}]"
        parts.append(name)
    joined = ", ".join(parts)
    if kind == "Function":
        var = "Result$" if ret == "string" else "Result"
        return f"{var} = {symbol}({joined})"
    return f"{symbol} {joined}".rstrip()


def parse_arity_min(arity: str) -> int | None:
    """'0-1' -> 0 ; '3-4' -> 3 ; '4, 8' or '2' -> None (no optional tail)."""
    m = re.fullmatch(r"(\d+)-(\d+)", arity.strip())
    return int(m.group(1)) if m else None


