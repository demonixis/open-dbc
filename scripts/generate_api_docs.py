def build_category_pages(rows: list[dict], helpmap: dict) -> tuple[dict, list[dict], dict]:
    """Group rows into categories and render one page per category."""
    by_cat: dict[str, list[list[dict]]] = {slug: [] for slug in CATEGORIES}

    core = [r for r in rows if r["surface"] == "Core"]
    groups: "OrderedDict[tuple, list[dict]]" = OrderedDict()
    for r in core:
        groups.setdefault((r["symbol"], r["kind"]), []).append(r)
    for (symbol, kind), grp in groups.items():
        help_entry = helpmap.get(symbol)
        cat = categorize(symbol, help_entry["cat"] if help_entry else None)
        by_cat[cat].append(grp)

    for r in rows:
        if r["surface"] in SURFACE_CATEGORY:
            by_cat[SURFACE_CATEGORY[r["surface"]]].append([r])

    search_index = []
    anchor_map: dict[str, str] = {}  # symbol -> "page.html#anchor" (core symbols)
    for slug, cat_groups in by_cat.items():
        if slug == "basics":
            continue
        cat_groups.sort(key=lambda g: g[0]["symbol"])
        meta = CATEGORIES[slug]
        entries_html, toc_entries, flat_rows = [], [], []
        used_anchors: set[str] = set()
        status_counts: dict[str, int] = {}
        profile_counts: dict[str, int] = {}
        for grp in cat_groups:
            symbol, kind = grp[0]["symbol"], grp[0]["kind"]
            help_entry = helpmap.get(symbol)
            anchor = slugify(symbol)
            if anchor in used_anchors:
                anchor += "-fn" if kind == "Function" else "-cmd"
            used_anchors.add(anchor)
            entry_html = render_entry(grp, help_entry, slug, anchor)
            entries_html.append(entry_html)
            tokens = group_status_tokens(grp)
            for token in tokens.split():
                status_counts[token] = status_counts.get(token, 0) + 1
            ptokens = group_profile_tokens(grp)
            for token in ptokens.split():
                profile_counts[token] = profile_counts.get(token, 0) + 1
            toc_entries.append((symbol, anchor, tokens, ptokens))
            flat_rows.extend(grp)
            if grp[0]["surface"] == "Core":
                anchor_map.setdefault(symbol, f"{slug}.html#{anchor}")
            profs = "DBC + DBPro" if len(grp) > 1 else grp[0]["profiles"]
            search_index.append({"s": symbol, "k": kind_label(kind), "p": profs,
                                 "u": f"{slug}.html#{anchor}", "c": meta["title"]})
        if not cat_groups:
            continue
        page = PAGE_TEMPLATE.format(
            title=esc(meta["title"]), blurb=esc(meta["blurb"]),
            counts=esc(counts_line(flat_rows)), n=len(toc_entries),
            filters=filter_panel_html(status_counts, profile_counts),
            toc=toc_html(toc_entries), content="\n".join(entries_html),
            note=esc(GENERATOR_NOTE),
        )
        (OUT / f"{slug}.html").write_text(page, encoding="utf-8")
        by_cat[slug] = cat_groups
    return by_cat, search_index, anchor_map


