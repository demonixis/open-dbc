def params_table(params: list[str], names: list[str] | None, min_arity: int | None) -> str:
    if not params:
        return '<p class="noparams">No parameters.</p>'
    rows = []
    for i, ptype in enumerate(params):
        name = names[i] if names and i < len(names) else generic_param_name(ptype, i + 1)
        optional = min_arity is not None and i >= min_arity
        note = []
        if ptype == "output":
            note.append("assigned by the command")
        if ptype == "any array":
            note.append("whole array (() marker)")
        if optional:
            note.append("optional")
        rows.append(
            f"<tr><td><code>{esc(name)}</code></td>"
            f"<td><code>{esc(ptype)}</code></td>"
            f"<td>{esc(', '.join(note)) if note else '—'}</td></tr>"
        )
    return ('<table class="params"><thead><tr><th>Parameter</th><th>Type</th>'
            "<th>Notes</th></tr></thead><tbody>" + "".join(rows) + "</tbody></table>")


def render_signature_block(row: dict, symbol: str, kind: str, help_entry: dict | None) -> str:
    typed = row["typed_overloads"]
    if typed in ("grammar form", "TBD"):
        return ""
    overloads = parse_overloads(typed)
    min_arity = parse_arity_min(row["arity"])
    parts = []
    for params, ret in overloads:
        names = None
        if help_entry:
            names = help_param_names(symbol, kind, help_entry["syntax"], len(params))
        sig = build_signature(symbol, kind, params, ret, names, min_arity if len(overloads) == 1 else None)
        parts.append('<div class="overload">')
        parts.append(f'<pre class="sig">{esc(sig)}</pre>')
        parts.append(f'<p class="typed">Typed signature: <code>{esc(", ".join(params) if params else "none")} '
                     f'&rarr; {esc(ret)}</code></p>')
        parts.append("<h4>Parameters</h4>")
        parts.append(params_table(params, names, min_arity if len(overloads) == 1 else None))
        if kind == "Function":
            parts.append(f'<p class="ret">Return value: <code>{esc(ret)}</code></p>')
        parts.append("</div>")
    return "".join(parts)


