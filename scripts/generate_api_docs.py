def load_help() -> dict[str, dict]:
    """Map normalized symbol -> {cat, desc, syntax}; only the Classic help folder is known."""
    result: dict[str, dict] = {}
    for line in DBC_EVIDENCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or line.startswith("kind\t"):
            continue
        _, name, _, pages = line.split("\t")
        folder = pages.split(",")[0].split("/")[0]
        if folder in HELP_FOLDER_CATEGORY:
            result.setdefault(name, {"cat": folder, "title": name, "desc": "", "syntax": ""})
    return result


