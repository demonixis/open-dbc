def validate_output(Output: Path) -> None:
    Pages = sorted(Output.glob("*.html"))
    if not Pages or not (Output / "index.html").is_file() or not (Output / "styles.css").is_file():
        raise SystemExit("HTML reference output is incomplete")
    Ids = {}
    Hrefs = {}
    for Page in Pages:
        Text = Page.read_text(encoding="utf-8")
        PageIds = re.findall(r'\bid="([^"]+)"', Text)
        if len(PageIds) != len(set(PageIds)):
            raise SystemExit(f"duplicate HTML id in {Page}")
        Ids[Page.name] = set(PageIds)
        Hrefs[Page.name] = re.findall(r'\bhref="([^"]+)"', Text)
        if Page.name == "index.html":
            IndexMatch = re.search(r"const INDEX = (\[.*\]);\nconst input =", Text)
            if not IndexMatch:
                raise SystemExit("HTML search index is missing or malformed")
            try:
                SearchEntries = json.loads(IndexMatch.group(1))
                Hrefs[Page.name].extend(Entry["u"] for Entry in SearchEntries)
            except (json.JSONDecodeError, KeyError, TypeError) as Error:
                raise SystemExit(f"HTML search index is malformed: {Error}") from Error
    for PageName, Links in Hrefs.items():
        for Link in Links:
            if "${" in Link or Link.startswith(("http://", "https://", "mailto:")):
                continue
            TargetName, Separator, Fragment = Link.partition("#")
            TargetName = TargetName or PageName
            Target = Output / TargetName
            if not Target.is_file():
                raise SystemExit(f"broken HTML link in {PageName}: {Link}")
            if Separator and Fragment and Fragment not in Ids.get(TargetName, set()):
                raise SystemExit(f"broken HTML anchor in {PageName}: {Link}")


def generate(Output: Path) -> None:
    global OUT
    OUT = Output
    OUT.mkdir(parents=True, exist_ok=True)
    helpmap = load_help()
    rows = language_catalogue()[0]

    (OUT / "styles.css").write_text(STYLES, encoding="utf-8")
    by_cat, search_index, anchor_map = build_category_pages(rows, helpmap)
    basics_count = build_basics_page(helpmap, search_index)
    matcher = build_symbol_matcher(rows)
    example_stats = {
        "dbc": build_examples_page("dbc", matcher, anchor_map, search_index),
        "dbpro": build_examples_page("dbpro", matcher, anchor_map, search_index),
    }
    build_index(by_cat, search_index, basics_count, len(rows), example_stats)

    print(f"DBC help: {len(helpmap)} pages parsed.")
    for slug in CATEGORIES:
        if slug == "basics":
            print(f"  basics: {basics_count} syntax elements")
        else:
            n = len(by_cat.get(slug, []))
            if n:
                print(f"  {slug}: {n} commands")
    for profile, (count, lines) in example_stats.items():
        print(f"  examples-{profile}: {count} programs ({lines} lines)")
    validate_output(OUT)
    print(f"Output: {OUT}")


def main() -> None:
    Parser = argparse.ArgumentParser(description="Generate and validate the OpenDBC HTML reference")
    Parser.add_argument("--output", type=Path, default=OUT)
    Parser.add_argument("--check", action="store_true",
                        help="generate into a temporary directory and validate every local link and anchor")
    Args = Parser.parse_args()
    if Args.check:
        with tempfile.TemporaryDirectory(prefix="opendbc-api-") as Directory:
            generate(Path(Directory))
        print("HTML reference generation check passed")
        return
    generate(Args.output)


if __name__ == "__main__":
    main()
