def crawler() -> list[Node]:
    legs = []
    for index, side in enumerate((-1, -1, -1, 1, 1, 1)):
        legs.append(Node(f"leg_upper_{index + 1}", (side * 1.2, 0, -1.0 + index % 3), (1.2, 0.3, 0.3), [
            Node(f"leg_lower_{index + 1}", (side * 1.0, -0.5, 0), (0.3, 1.0, 0.3))]))
    claws = []
    for index, side in enumerate((-1, 1)):
        claws.append(Node(f"claw_arm_{index + 1}", (side * 1.0, 0, 1.6), (0.4, 0.4, 1.2), [
            Node(f"pincer_{index + 1}", (0, 0, 1.2), (0.8, 0.3, 0.6))]))
    return [Node("chassis", (0, 1.2, 0), (2.4, 0.8, 3.0), [
        Node("carapace", (0, 0.6, 0), (2.2, 0.5, 2.6), [Node("eye", (0, 0.4, 1.0), (0.4, 0.4, 0.4))] + claws + legs)])]


def crawler_motion(walking: bool):
    def motion(name: str, phase: float):
        swing = math.sin(phase * 2.0 * math.pi)
        if name.startswith("leg_upper_"):
            sign = 1 if int(name[-1]) % 2 else -1
            return sign * (25.0 if walking else 3.0) * swing, (0.0, 0.0, 0.0)
        if name == "chassis":
            return 0.0, (0.0, 0.1 * abs(swing), 0.0)
        return 0.0, (0.0, 0.0, 0.0)
    return motion


