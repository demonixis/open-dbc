def fixtures() -> dict[str, bytes]:
    files = {
        "models/dome.x": quirk_plane(),
        "models/ARMOUR.X": x_file(armoured_vehicle()),
        "models/turret/attack.x": x_file(articulated_turret(),
                                         animation_block(articulated_turret(), 20, lambda n, p: (
                                             30.0 * math.sin(p * 2 * math.pi) if n == "head" else 0.0, (0.0, 0.0, 0.0)))),
        "models/idle.x": x_file(worker(), animation_block(worker(), 20, worker_motion(False))),
        "models/walk.x": x_file(worker(), animation_block(worker(), 25, worker_motion(True))),
        "models/rider.x": x_file(rider(), animation_block(rider(), 20, lambda n, p: (
            10.0 * math.sin(p * 2 * math.pi) if n == "body" else 0.0, (0.0, 0.0, 0.0)))),
        "obj/CrawlerIdle.x": x_file(crawler(), animation_block(crawler(), 20, crawler_motion(False))),
        "obj/CrawlerWalk.x": x_file(crawler(), animation_block(crawler(), 15, crawler_motion(True))),
    }

    sunset = ramp(256, (20, 10, 60), (250, 170, 60))
    files["bmp/loading.bmp"] = rle8(640, 480, sunset, lambda x, y: (y * 255 // 479) if (x // 40 + y // 40) % 2 else
                                    255 - (y * 255 // 479))
    files["bmp/backdrop.bmp"] = rle4(640, 480, ramp(16, (10, 40, 30), (140, 220, 120)),
                                     lambda x, y: min(15, (y // 30 + (x // 80)) % 16))
    files["bmp/badge.bmp"] = rle8(640, 480, ramp(256, (0, 0, 40), (255, 220, 120)),
                                  lambda x, y: 64 + (x // 32 + y // 32) % 4 * 48 if (x - 320) ** 2 + (y - 240) ** 2 < 200 ** 2 else 0)
    glow = ramp(256, (0, 0, 0), (255, 255, 200))
    files["bmp/beam.bmp"] = rle8(64, 256, glow, lambda x, y: max(0, 255 - abs(x - 32) * 10) if 16 < y < 240 else 0)
    files["bmp/spark.bmp"] = rle8(64, 64, glow, lambda x, y: max(0, 255 - int(math.hypot(x - 32, y - 32) * 9)))
    files["bmp/stone.bmp"] = bmp24(64, 64, lambda x, y: (90 + (x * 3 + y * 5) % 50, 85 + (x * 5 + y * 3) % 40, 80))
    files["bmp/brick.bmp"] = bmp8(128, 128, [(c, c // 2 + 20, c // 3) for c in range(256)],
                                  lambda x, y: brick(x, y)[0])
    files["bmp/brick.dds"] = dxt1(128, 128, brick)
    files["sound/chime.wav"] = wav(chime(), 16)
    files["sound/thump.wav"] = wav(thump(), 16)
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate the Classic compatibility test fixtures")
    parser.add_argument("--check", action="store_true", help="fail when a tracked fixture is stale")
    args = parser.parse_args()
    generated = fixtures()
    for relative, content in generated.items():
        path = OUTPUT / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit(f"classic fixture is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    tracked = {path.relative_to(OUTPUT).as_posix() for path in OUTPUT.rglob("*") if path.is_file()}
    unexpected = sorted(tracked - set(generated))
    if unexpected:
        raise SystemExit(f"unexpected files in {OUTPUT}: {', '.join(unexpected)}")
    print("Classic fixtures are current" if args.check else f"Wrote {len(generated)} Classic fixtures")


if __name__ == "__main__":
    main()
