def wav(samples, bits: int, rate: int = 22050) -> bytes:
    if bits == 16:
        data = b"".join(struct.pack("<h", max(-32767, min(32767, int(s * 32767)))) for s in samples)
    else:
        data = bytes(max(0, min(255, int(128 + s * 127))) for s in samples)
    block = bits // 8
    fmt_chunk = struct.pack("<4sIHHIIHH", b"fmt ", 16, 1, 1, rate, rate * block, block, bits)
    return struct.pack("<4sI4s", b"RIFF", 4 + len(fmt_chunk) + 8 + len(data), b"WAVE") + fmt_chunk + \
        struct.pack("<4sI", b"data", len(data)) + data


def chime(rate: int = 22050):
    count = rate // 2
    return [0.5 * math.exp(-4.0 * i / count) * math.sin(2 * math.pi * (660 + 220 * (i / count)) * i / rate)
            for i in range(count)]


def thump(rate: int = 22050):
    count = rate // 4
    state, output = 12345, []
    for i in range(count):
        state = (1103515245 * state + 12345) & 0x7FFFFFFF
        noise = (state / 0x7FFFFFFF) * 2.0 - 1.0
        envelope = math.exp(-12.0 * i / count)
        output.append(envelope * (0.6 * math.sin(2 * math.pi * 70 * i / rate) + 0.3 * noise))
    return output


