def worker_motion(walking: bool):
    def motion(name: str, phase: float):
        swing = math.sin(phase * 2.0 * math.pi)
        if name in ("thigh_r", "arm_l"):
            return (30.0 if walking else 4.0) * swing, (0.0, 0.0, 0.0)
        if name in ("thigh_l", "arm_r"):
            return -(30.0 if walking else 4.0) * swing, (0.0, 0.0, 0.0)
        if name == "pelvis":
            return 0.0, (0.0, 0.15 * abs(swing), 1.5 * phase if walking else 0.0)
        return 0.0, (0.0, 0.0, 0.0)
    return motion


