def bmp_header(width: int, height: int, bits: int, compression: int, palette: bytes, data: bytes) -> bytes:
    offset = 14 + 40 + len(palette)
    file_header = struct.pack("<2sIHHI", b"BM", offset + len(data), 0, 0, offset)
    info = struct.pack("<IiiHHIIiiII", 40, width, height, 1, bits, compression, len(data), 2835, 2835,
                       len(palette) // 4, len(palette) // 4)
    return file_header + info + palette + data


def bmp24(width: int, height: int, pixel) -> bytes:
    rows = []
    for y in range(height - 1, -1, -1):
        row = bytearray()
        for x in range(width):
            r, g, b = pixel(x, y)
            row += bytes((b, g, r))
        row += b"\0" * ((4 - len(row) % 4) % 4)
        rows.append(bytes(row))
    return bmp_header(width, height, 24, 0, b"", b"".join(rows))


def palette_bytes(colours) -> bytes:
    return b"".join(bytes((b, g, r, 0)) for r, g, b in colours)


def indexed_rows(width: int, height: int, index):
    return [[index(x, y) for x in range(width)] for y in range(height - 1, -1, -1)]


def bmp8(width: int, height: int, colours, index) -> bytes:
    data = bytearray()
    for row in indexed_rows(width, height, index):
        data += bytes(row) + b"\0" * ((4 - width % 4) % 4)
    return bmp_header(width, height, 8, 0, palette_bytes(colours), bytes(data))


def rle8(width: int, height: int, colours, index) -> bytes:
    data = bytearray()
    for row in indexed_rows(width, height, index):
        x = 0
        while x < width:
            run = 1
            while x + run < width and run < 255 and row[x + run] == row[x]:
                run += 1
            data += bytes((run, row[x]))
            x += run
        data += b"\0\0"
    data += b"\0\1"
    return bmp_header(width, height, 8, 1, palette_bytes(colours), bytes(data))


def rle4(width: int, height: int, colours, index) -> bytes:
    data = bytearray()
    for row in indexed_rows(width, height, index):
        x = 0
        while x < width:
            run = 1
            while x + run < width and run < 254 and row[x + run] == row[x]:
                run += 1
            data += bytes((run, (row[x] << 4) | row[x]))
            x += run
        data += b"\0\0"
    data += b"\0\1"
    return bmp_header(width, height, 4, 2, palette_bytes(colours), bytes(data))


def ramp(count: int, start, end):
    return [tuple(int(start[c] + (end[c] - start[c]) * i / max(1, count - 1)) for c in range(3)) for i in range(count)]


def dxt1(width: int, height: int, pixel) -> bytes:
    def pack565(rgb):
        r, g, b = rgb
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

    def unpack565(value):
        return (((value >> 11) & 31) * 255 // 31, ((value >> 5) & 63) * 255 // 63, (value & 31) * 255 // 31)

    blocks = bytearray()
    for by in range(0, height, 4):
        for bx in range(0, width, 4):
            texels = [pixel(bx + x, by + y) for y in range(4) for x in range(4)]
            luminance = [sum(t) for t in texels]
            c0, c1 = pack565(texels[luminance.index(max(luminance))]), pack565(texels[luminance.index(min(luminance))])
            if c0 < c1:
                c0, c1 = c1, c0
            if c0 == c1:
                indices = 0
            else:
                p0, p1 = unpack565(c0), unpack565(c1)
                palette = [p0, p1, tuple((2 * a + b) // 3 for a, b in zip(p0, p1)),
                           tuple((a + 2 * b) // 3 for a, b in zip(p0, p1))]
                indices = 0
                for i, texel in enumerate(texels):
                    best = min(range(4), key=lambda k: sum((texel[c] - palette[k][c]) ** 2 for c in range(3)))
                    indices |= best << (2 * i)
            blocks += struct.pack("<HHI", c0, c1, indices)
    header = struct.pack("<4sIIIIIII44sIIIIIIIIIIIII", b"DDS ", 124, 0x1 | 0x2 | 0x4 | 0x1000 | 0x80000,
                         height, width, len(blocks), 0, 0, b"\0" * 44,
                         32, 0x4, 0x31545844, 0, 0, 0, 0, 0, 0x1000, 0, 0, 0, 0)
    return header + bytes(blocks)


def brick(x: int, y: int):
    row = y // 16
    mortar = y % 16 == 0 or (x + (8 if row % 2 else 0)) % 32 == 0
    if mortar:
        return (190, 186, 176)
    shade = 120 + (x * 7 + y * 13 + row * 29) % 40
    return (shade + 40, shade // 2 + 20, shade // 3)


